#!/usr/bin/env python3
"""Download-time benchmarks on one machine, with every peer's upload capped.

Over loopback a single seeder can push gigabytes per second, which would hide
everything interesting. Real peers sit behind home uplinks, so every client
here runs with --upload-limit (default 2 MB/s) and the numbers measure what
the swarm logic does with that bandwidth.

  1. Seeder scaling: one client downloads a file that N clients already have.
  2. Flash crowd: K clients start downloading the same file at the same
     moment from a single original seed, with and without partial sharing
     (serving pieces before the download finishes).

    make && python3 tests/benchmark.py            # writes benchmarks/RESULTS.md
"""
import argparse
import hashlib
import os
import platform
import statistics
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from integration_test import ROOT, PIECE, Cluster, join, write_random  # noqa: E402

MB = 1024 * 1024


def same_file(path, digest):
    with open(path, "rb") as f:
        return hashlib.sha1(f.read()).hexdigest() == digest


def seeder_scaling(args, seeders, size):
    """Seconds for one fresh client to download `size` bytes held by `seeders` peers."""
    cl = Cluster(args)
    try:
        flags = ["--upload-limit", str(args.limit_kb)]
        owner = cl.client("owner", "owner", group="g", flags=flags)
        data = write_random(cl.path("f.bin"), size, 1)
        digest = hashlib.sha1(data).hexdigest()
        owner.cmd(f"upload_file g {cl.path('f.bin')}")
        # Turn N-1 more clients into full seeders (not timed).
        extra = []
        for i in range(seeders - 1):
            peer = cl.client(f"s{i}", f"s{i}", flags=flags)
            join(owner, peer, "g")
            extra.append(peer)
        for i, peer in enumerate(extra):
            peer.send(f"download_file g f.bin {cl.path(f's{i}.bin')}")
        for peer in extra:
            peer.wait_for(r"Download completed", timeout=300)

        d = cl.client("d", "d", flags=flags)
        join(owner, d, "g")
        start = time.monotonic()
        d.cmd(f"download_file g f.bin {cl.path('d.bin')}", r"Starting download")
        d.wait_for(r"Download completed", timeout=300)
        elapsed = time.monotonic() - start
        assert same_file(cl.path("d.bin"), digest), "corrupt download"
        return elapsed
    finally:
        cl.close()


def flash_crowd(args, downloaders, size, partial):
    """Seconds until all `downloaders` clients, started together, have the file."""
    cl = Cluster(args)
    try:
        flags = ["--upload-limit", str(args.limit_kb)] + ([] if partial else ["--no-partial-sharing"])
        owner = cl.client("owner", "owner", group="g", flags=flags)
        data = write_random(cl.path("f.bin"), size, 2)
        digest = hashlib.sha1(data).hexdigest()
        owner.cmd(f"upload_file g {cl.path('f.bin')}")
        crowd = []
        for i in range(downloaders):
            peer = cl.client(f"p{i}", f"p{i}", flags=flags)
            join(owner, peer, "g")
            crowd.append(peer)
        start = time.monotonic()
        for i, peer in enumerate(crowd):
            peer.send(f"download_file g f.bin {cl.path(f'p{i}.bin')}")
        for peer in crowd:
            peer.wait_for(r"Download completed", timeout=600)
        elapsed = time.monotonic() - start
        for i in range(downloaders):
            assert same_file(cl.path(f"p{i}.bin"), digest), f"p{i} got a corrupt copy"
        return elapsed
    finally:
        cl.close()


def median_of(runs, fn):
    times = [fn() for _ in range(runs)]
    return statistics.median(times), times


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tracker", default=os.path.join(ROOT, "tracker", "tracker"))
    ap.add_argument("--client", default=os.path.join(ROOT, "client", "client"))
    ap.add_argument("--limit-kb", type=int, default=2048, help="upload cap per peer, KB/s")
    ap.add_argument("--size-mb", type=int, default=16, help="file size for seeder scaling")
    ap.add_argument("--crowd-size-mb", type=int, default=8, help="file size for the flash crowd")
    ap.add_argument("--crowd", type=int, default=8, help="downloaders in the flash crowd")
    ap.add_argument("--repeats", type=int, default=3)
    ap.add_argument("--out", default=os.path.join(ROOT, "benchmarks", "RESULTS.md"))
    args = ap.parse_args()
    args.tracker, args.client = os.path.abspath(args.tracker), os.path.abspath(args.client)
    args.wire = "framed"
    limit_mb = args.limit_kb / 1024

    lines = [
        "# Benchmark results",
        "",
        f"Generated by `tests/benchmark.py` on {platform.platform()} ({os.cpu_count()} CPUs), "
        f"all peers on loopback with uploads capped at {limit_mb:g} MB/s each. "
        f"Median of {args.repeats} runs; piece size {PIECE // 1024} KB.",
        "",
        f"## Seeder scaling: one client downloads a {args.size_mb} MB file",
        "",
        "| Seeders | Time (s) | Throughput (MB/s) | Speed-up | Runs (s) |",
        "|---:|---:|---:|---:|---|",
    ]
    size = args.size_mb * MB
    base = None
    for n in [1, 2, 4, 8]:
        med, runs = median_of(args.repeats, lambda: seeder_scaling(args, n, size))
        base = base or med
        row = (f"| {n} | {med:.2f} | {args.size_mb / med:.1f} | {base / med:.1f}x | "
               f"{', '.join(f'{t:.2f}' for t in runs)} |")
        print(row, flush=True)
        lines.append(row)

    crowd_size = args.crowd_size_mb * MB
    lines += [
        "",
        f"## Flash crowd: {args.crowd} clients fetch a {args.crowd_size_mb} MB file from one seed at once",
        "",
        "| Partial sharing | Time until all finish (s) | Runs (s) |",
        "|---|---:|---|",
    ]
    results = {}
    for partial in [False, True]:
        med, runs = median_of(args.repeats, lambda: flash_crowd(args, args.crowd, crowd_size, partial))
        results[partial] = med
        row = f"| {'on' if partial else 'off'} | {med:.2f} | {', '.join(f'{t:.2f}' for t in runs)} |"
        print(row, flush=True)
        lines.append(row)
    lines += [
        "",
        f"Partial sharing finishes the crowd {results[False] / results[True]:.1f}x faster. "
        f"Without it the seed alone uploads {args.crowd} x {args.crowd_size_mb} MB; the lower bound is "
        f"{args.crowd * args.crowd_size_mb / limit_mb:.0f} s. With it, every downloader also uploads; "
        f"the seed must still send each piece at least once, so the lower bound is "
        f"{args.crowd_size_mb / limit_mb:.0f} s.",
        "",
    ]

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(lines))
    print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
